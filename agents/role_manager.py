def _resolve_role(role: AgentRole | str) -> AgentRole:
    """统一处理 role 为 AgentRole 类型"""
    if isinstance(role, AgentRole):
        return role
    try:
        return AgentRole(role)
    except ValueError:
        return AgentRole.QIXIA

def get_role_prompt(role: AgentRole | str) -> str:
    return ROLE_CONFIGS[_resolve_role(role)]["system_prompt"]

def get_role_info(role: AgentRole | str) -> dict:
    return ROLE_CONFIGS[_resolve_role(role)]

def get_all_roles() -> list:
    return list(AgentRole)
